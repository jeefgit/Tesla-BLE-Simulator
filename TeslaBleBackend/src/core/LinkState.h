#pragma once

#include <stdint.h>

// ---------------------------------------------------------------------------
// LinkState：数据源链路的抽象状态
//
// UI 只认识这个枚举，不再依赖具体的传输实现（BLE / OBD / 演示剧本）。
// 各数据源自行把自己的内部状态映射成 LinkState。
// ---------------------------------------------------------------------------
enum class LinkState : uint8_t {
  Idle,          // 尚未开始
  Scanning,      // 正在扫描/发现目标
  Connecting,    // 正在连接
  Ready,         // 链路已通，可以收发
  Reconnecting,  // 断线，等待重连
  Error,         // 不可恢复错误（可选，UI 可按 Idle 处理）
};
